"""Deterministic stage client for running the real container path without an LLM.

``TemplateStageClient`` produces fixed, templated stage text and a small Python
module plus a pytest file. It is *not* CrewAI and *not* Gemini
(``uses_live_provider`` is False). Its purpose is to let the Developer–Tester
repair loop run against the real Docker runtime: the first ``fail_first``
developer iterations deliberately ship a defect, the container's pytest run
fails, and the next iteration uses that runtime feedback to ship the fix.
The pass/fail decision always comes from the container, never from this class.
"""

import json
import re

from cloudeq.plane2_agents.agents.stage_client import StageDraft, StageRunRequest
from cloudeq.plane2_agents.models import StageName
from cloudeq.shared.contracts.models import TEST_COMMAND_ALLOWLIST, RuntimeFile

MODULE_PATH = "forge_feature.py"
TEST_PATH = "test_forge_feature.py"


class TemplateStageClient:
    uses_live_provider = False
    live_crewai = False
    live_gemini = False
    label = "template (deterministic, no LLM)"

    def __init__(self, *, fail_first: int = 0) -> None:
        self.fail_first = max(0, fail_first)
        self.generated: dict[str, list[RuntimeFile]] = {}

    def run_stage(self, request: StageRunRequest) -> StageDraft:
        prompt = " ".join(request.prompt.split())[:200]
        files: list[RuntimeFile] = []
        commands: list[str] = []
        if request.stage is StageName.DEVELOPMENT:
            iteration = request.iteration or 1
            defective = iteration <= self.fail_first
            files = _files(prompt, defective=defective)
            self.generated[request.task_id] = files
            summary = f"Iteration {iteration}: wrote {MODULE_PATH} and {TEST_PATH}" + (
                " (template defect injected to exercise the repair loop)." if defective else "."
            )
            if request.prior_feedback:
                summary += " Used the previous runtime test output as feedback."
        elif request.stage is StageName.TESTING:
            commands = [TEST_COMMAND_ALLOWLIST[0]]
            summary = "Run the generated pytest suite inside the sandbox container."
        else:
            summary = _plan(request.stage, prompt)
        return StageDraft(
            task_id=request.task_id,
            trace_id=request.trace_id,
            stage=request.stage,
            summary=summary,
            files=files,
            test_commands=commands,
        )


def _plan(stage: StageName, prompt: str) -> str:
    texts = {
        StageName.REQUIREMENTS: f"Requirement: provide a callable that reports '{prompt}' "
        "with status 'ok', covered by an automated test.",
        StageName.PLANNING: "Plan: (1) write the module, (2) write the pytest, "
        "(3) run tests in the sandbox, (4) repair until green or budget is spent.",
        StageName.ARCHITECTURE: f"Architecture: single module {MODULE_PATH} exposing run(); "
        f"tests in {TEST_PATH}; no network, no host execution.",
        StageName.DEVOPS: "Release decision recorded after the runtime reported a pass.",
    }
    return texts.get(stage, f"{stage.value} stage completed.")


def _identifier(prompt: str) -> str:
    words = re.findall(r"[a-z0-9]+", prompt.lower())[:6]
    return "_".join(words) or "feature"


def _files(prompt: str, *, defective: bool) -> list[RuntimeFile]:
    literal = json.dumps(prompt)  # a JSON string literal is also a valid Python literal
    status = '"todo"' if defective else '"ok"'
    module = (
        '"""Generated by FORGE SPAN (template stage client)."""\n\n'
        f"FEATURE = {literal}\n"
        f'NAME = "{_identifier(prompt)}"\n\n\n'
        "def run() -> dict[str, str]:\n"
        f'    return {{"feature": FEATURE, "name": NAME, "status": {status}}}\n'
    )
    test = (
        "from forge_feature import FEATURE, NAME, run\n\n\n"
        "def test_run_reports_ok() -> None:\n"
        '    assert run()["status"] == "ok"\n\n\n'
        "def test_run_echoes_feature() -> None:\n"
        '    assert run()["feature"] == FEATURE\n'
        '    assert run()["name"] == NAME\n'
    )
    return [
        RuntimeFile(relative_path=MODULE_PATH, content=module),
        RuntimeFile(relative_path=TEST_PATH, content=test),
    ]
